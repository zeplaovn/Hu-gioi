'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const H = require('../engine/game.js');
const C = require('../engine/protocol/commands.js');
const NOW = 1_800_000_000_000;
const profile = { name: 'Lý Vô Thường', gender: 'nam', age: 18, race: 'nhan', roots: [72, 61, 45, 44, 33], rootType: 'Song', talent: { tuongMao: 2, phucDuyen: 2, canCot: 2, ngoTinh: 1, vanKhi: 1 }, destiny: 'exp' };
const make = () => new H.Game(H.createCharacter(profile, NOW, () => 0), () => 0);
const claim = (g, id) => C.execute(g, { type: 'claimQuest', payload: { id } }, NOW);

test('tuyến tân thủ kiểm tra thứ tự, điều kiện, thưởng một lần và giữ tiến độ khi tải lại', () => {
  let g = make();
  const qs = H.NOVICE_QUESTS;
  assert.throws(() => claim(g, qs[1].id), /Chưa thể/);
  assert.throws(() => claim(g, qs[0].id), /Chưa thể/);
  g.s.progress.meditate = 60;
  const before = g.s.stone;
  claim(g, qs[0].id);
  assert.equal(g.s.stone, before + qs[0].stone);
  assert.throws(() => claim(g, qs[0].id), /Chưa thể/);
  g = new H.Game(H.normalize(g.s, NOW, H.Game), () => 0);
  assert.equal(g.noviceQuestInfo().quest.id, qs[1].id);
  C.execute(g, { type: 'joinSect', payload: { id: H.SECTS[0].id } }, NOW);
  claim(g, qs[1].id);
  assert.throws(() => claim(g, qs[2].id), /Chưa thể/);
  g.s.sect.missionsDone = 1;
  claim(g, qs[2].id);
  g.s.exploration.last = { kind: 'npc', start: NOW - 600000, end: NOW, name: '', text: '' };
  claim(g, qs[3].id);
  g.s.progress.alchemy = 1;
  claim(g, qs[4].id);
  g.s.stage = 3;
  claim(g, qs[5].id);
  g.s.stage = H.F.STAGES[0];
  claim(g, qs[6].id);
  assert.throws(() => claim(g, qs[7].id), /Chưa thể/);
  g.s.realm = 1; g.s.stage = 1;
  claim(g, qs[7].id);
  g = new H.Game(H.normalize(g.s, NOW, H.Game), () => 0);
  assert.equal(g.noviceQuestInfo().quest, null);
  assert.equal(g.s.claimed.filter(id => id.startsWith('novice_')).length, qs.length);
});

test('nhân vật đã tiến xa vẫn nhận được các bước theo tiến độ hiện có', () => {
  const g = make();
  g.s.realm = 1;
  g.s.progress.meditate = 60;
  claim(g, 'novice_meditate');
  assert.equal(g.noviceQuestInfo().quest.id, 'novice_sect');
  assert.equal(g.noviceQuestInfo().ready, false);
});
