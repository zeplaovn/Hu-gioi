import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { parseCsv } from './csv.mjs';
const root = new URL('../', import.meta.url);
const read = p => readFileSync(new URL(p, root), 'utf8');
const csv = p => parseCsv(read(p));
const doc = 'docs/design/00_Tuyen_Truyen_Chinh_Ba_Gioi_12_Chuong.md';
const sections = read(doc).split(/^### Chương /m).slice(1);
const stageGates = [0, 1, 3, 5, 6, 7, 8, 9, 10, 11, 13, 14];
const chapters = sections.map((text, i) => {
  const [heading, ...lines] = text.split('\n');
  // Author instructions and later volume headers are not spoken narration.
  const narrative = lines.join('\n').split(/\n(?:\*\*|## )/)[0].trim();
  return { id: `CH-${String(i + 1).padStart(2, '0')}`, title: `Chương ${heading.trim()}`, stage: stageGates[i], paragraphs: narrative.split(/\n\s*\n/).filter(Boolean), source: doc };
});
if (chapters.length !== 12) throw new Error('Cần đúng 12 chương');
const assets = JSON.parse(read('data/asset-manifest.json'));
const images = Object.fromEntries(assets.filter(a => a.canonical_id && !a.internal && a.quality !== 'can_sua_khung').map(a => [a.canonical_id, a.path]));
// Prefer idle pose over terminal/death frames for bestiary portraits.
for (const a of assets.filter(a => a.canonical_id && a.source.includes('/dung_yen/') && !a.internal && a.quality !== 'can_sua_khung')) images[a.canonical_id] = a.path;
const content = {
  version: '1.6.1', chapters,
  monsters: csv('data/combat/monster_boss_lore_v14.csv').map(r => ({ ...r, image: images[r.monster_id] || null })),
  items: ['dan_duoc', 'linh_duoc', 'nguyen_lieu', 'trang_bi'].flatMap(type => csv(`data/${type}.csv`).map(r => ({ ...r, category: type, image: images[r.id] || null }))),
};
if (content.monsters.length !== 30) throw new Error('Cần đúng 30 hồ sơ Bách Quái');
const outputs = [['apps/web/src/content.generated.js', '// Generated by tools/gen-content.mjs.\nexport default '+JSON.stringify(content,null,2)+';\n']];
for (const [path, text] of outputs) {
  const url = new URL(path, root);
  if (process.argv.includes('--check')) { if (!existsSync(url) || read(path) !== text) throw new Error('LỆCH '+path); }
  else writeFileSync(url,text);
}
console.log(`content: ${chapters.length} chương, ${content.monsters.length} quái/boss, ${content.items.length} vật phẩm`);
