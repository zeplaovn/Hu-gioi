import { readFileSync, writeFileSync } from 'node:fs';
import { parseCsv } from './csv.mjs';
const read = name => JSON.parse(readFileSync(`data/social/${name}.json`, 'utf8'));
const daily = read('daily_dialogues'), events = read('random_events'), story = read('story_dialogues').scenes;
const scenes = [...daily, ...events, ...story.map(s => ({ ...s, scene_id: s.dialogue_id, kind: 'story' }))];
const npcs = [...new Map(scenes.map(s => [s.npc_id, { id: s.npc_id, name: s.npc_name, faction: s.faction }])).values()];
const gifts = parseCsv(readFileSync('data/social/gift_catalog.csv', 'utf8'));
if (npcs.length !== 19 || daily.length !== 76 || events.length !== 38 || story.length !== 95 || gifts.length !== 36) throw Error('Social content count mismatch');
if (new Set(scenes.map(s => s.scene_id)).size !== scenes.length) throw Error('Duplicate scene');
const quote = x => "'" + JSON.stringify(x).replaceAll("'", "''") + "'::jsonb";
const content = { version: '1.1', npcs, scenes, gifts, preferences: read('gift_preferences').preferences, config: read('social_config') };
const sql = `-- Generated by tools/gen-social.mjs; server-only source.\ninsert into game.rules(key,value) values ('social_content',${quote(content)})\non conflict(key) do update set value=excluded.value;\n`;
const target = 'supabase/migrations/20261020133000_social_content.sql';
if (process.argv.includes('--check')) {
 if (readFileSync(target,'utf8') !== sql) throw Error(`${target} is stale`);
} else writeFileSync(target, sql);
console.log(`Social: ${npcs.length} NPC, ${scenes.length} scenes, ${gifts.length} gifts`);
