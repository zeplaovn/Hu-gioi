/* Pure numerical model. Port of docs/cong_thuc_game.py; stages are zero based. */
(function(root){
'use strict';
const D=typeof module!=='undefined'&&module.exports?require('./balance-data.js'):root.HU_BALANCE;
const {P,REALMS,STAGES,BOLTS}=D;
const clamp=(x,a,b)=>Math.max(a,Math.min(b,x));
const sum=xs=>xs.reduce((a,b)=>a+b,0);
const range=n=>Array.from({length:n},(_,i)=>i);
const F={...D};
F.stage_time=(r,s)=>P.T0*(1+r)**P.T_POW*(P.W_MIN+(P.W_MAX-P.W_MIN)*(STAGES[r]>1?s/(STAGES[r]-1):.5));
F.base_rate=r=>P.R0*P.K_RATE**r;
F.ref_rate=(r,s)=>F.base_rate(r)*P.U**(s/STAGES[r]);
F.exp_need=(r,s)=>F.stage_time(r,s)*F.ref_rate(r,s);
F.cultivation_rate=(r,add=0,mults=[],rootType='Song',prestige=1)=>F.base_rate(r)*(1+add)*mults.reduce((a,b)=>a*(1+b),1)*D.LINH_CAN_RATE[rootType]/D.LINH_CAN_RATE.Song*prestige;
F.time_to_goal=(need,have,rate)=>rate>0?Math.max(0,(need-have)/rate):Infinity;
F.stat_scale=(r,s)=>P.K_STAT**r*P.K_STAGE**(s/STAGES[r]);
F.stats=(r,s,rootType=null)=>{const k=F.stat_scale(r,s),c=D.LINH_CAN_COMBAT[rootType]||1;return {HP:P.HP0*k*c,ATK:P.ATK0*k*c,DEF:P.DEF0*k,SPD:P.SPD0*P.K_SPD**(r+s/STAGES[r])}};
F.item_flat_bonus=(r,sub)=>F.stat_scale(r,0)*.05*2**sub;
F.diminishing=(x,max,k)=>x>0?max*x/(x+k):0;
F.crit_rate=x=>Math.min(.75,.05+F.diminishing(x,.70,1));
F.dodge_rate=x=>Math.min(.60,F.diminishing(x,.60,1));
F.damage=(atk,def,skill=1,pen=0,crit=false,critDmg=1.5)=>Math.max(1,skill*atk*atk/Math.max(Number.MIN_VALUE,atk+def*(1-clamp(pen,0,1)))*(crit?critDmg:1));
F.combat_power=(hp,atk,def,cr=.05,cd=1.5)=>Math.sqrt(hp*(1+def/Math.max(Number.MIN_VALUE,atk))*atk*(1+cr*(cd-1)));
F.win_probability=(player,enemy,k=3)=>player>0?1/(1+(enemy/player)**k):0;
F.monster_cp=(r,s,kind='thường')=>{const x=F.stats(r,s);return F.combat_power(x.HP,x.ATK,x.DEF)*D.MONSTER_MULT[kind]};
F.p_base=r=>Math.max(P.P_FLOOR,P.P_START-P.P_DROP*r);
F.p_breakthrough=(r,s,bonus=0,pity=0,rootBonus=0)=>Math.min(P.P_CAP,(s===STAGES[r]-1?F.p_base(r)*P.P_REALM_FACTOR:Math.min(.99,F.p_base(r)+P.P_STAGE_BONUS))+F.diminishing(bonus,P.BONUS_MAX,P.BONUS_K)+rootBonus+Math.min(pity,P.PITY_MAX)*P.PITY_STEP);
F.on_breakthrough_fail=exp=>exp*(1-P.FAIL_EXP_LOSS);
F.tribulation_total=(r,rootType=null,mult=1.5)=>F.stats(r,STAGES[r]-1).HP*mult*(D.LINH_CAN_TRIB[rootType]||1);
F.tribulation_bolts=(r,rootType=null)=>{const n=Math.min(BOLTS[r],999);return range(n).map(k=>F.tribulation_total(r,rootType)/n*(.5+k/n))};
function survive(bolts,hp,shield,red,heal,reported){let cur=hp+shield;for(let i=0;i<bolts.length;i++){cur-=bolts[i]*(1-red);if(cur<=0)return [false,i];cur=Math.min(cur+heal,hp+shield)}return [true,reported]}
F.survive_tribulation=(r,hp,shield=0,red=0,heal=0,rootType=null)=>survive(F.tribulation_bolts(r,rootType),hp,shield,red,heal,BOLTS[r]);
F.realm_map=r=>r<5?'Hạ Giới':r<9?'Linh Giới':'Tiên Giới';
F.bolts_of=(r,alt=false)=>alt&&r===8?D.DO_KIEP_ALT:BOLTS[r];
F.bolts_by_map=(name,alt=false,ascend=false,daoTo=false)=>sum(range(14).filter(r=>F.realm_map(r)===name&&(r!==13||daoTo)).map(r=>F.bolts_of(r,alt)+(ascend?(D.ASCEND_BOLTS[r]||0):0)));
F.tribulation_avg_bolt=(r,rootType=null)=>BOLTS[r]?F.tribulation_total(r,rootType)/Math.min(BOLTS[r],999):0;
F.upgrade_base_cost=(r,effect,payback=P.PAYBACK0)=>F.base_rate(r)*effect*payback;
F.cost=(base,growth,owned)=>base*growth**owned;
F.bulk_cost=(base,growth,owned,k)=>growth===1?base*k:base*growth**owned*Math.expm1(k*Math.log(growth))/(growth-1);
F.max_buy=(money,base,growth,owned)=>{if(base<=0||money<F.cost(base,growth,owned))return 0;if(growth===1)return Math.floor(money/base);let k=Math.max(0,Math.floor(Math.log1p(money*(growth-1)/F.cost(base,growth,owned))/Math.log(growth)));while(k>0&&F.bulk_cost(base,growth,owned,k)>money)k--;while(F.bulk_cost(base,growth,owned,k+1)<=money)k++;return k};
F.offline_cap=(level=0)=>Math.min(P.OFF_CAP_MAX,P.OFF_CAP+7200*level);
F.offline_efficiency=(level=0)=>Math.min(1,P.OFF_EFF+.05*level);
F.offline_gain=(rate,elapsed,cap=0,eff=0)=>elapsed<=0?0:rate*Math.min(elapsed,F.offline_cap(cap))*F.offline_efficiency(eff);
F.prestige_k=()=>F.exp_need(P.PRESTIGE_K_REALM,0);
F.dao_van=exp=>Math.floor((Math.max(0,exp)/F.prestige_k())**P.PRESTIGE_POW);
F.prestige_mult=points=>1+P.PRESTIGE_COEF*points;
F.exp_for_dao_van=target=>F.prestige_k()*target**(1/P.PRESTIGE_POW);
F.price_ha=(tier,sub=0)=>P.PRICE0*P.PRICE_STEP**tier*2**sub;
F.craft_time=tier=>30*2.2**tier;
F.craft_success=(tier,skill)=>clamp(.90-.12*(tier-skill),.05,.95);
F.craft_quality=(tier,skill,rng=Math.random)=>{const u=Math.max(Number.MIN_VALUE,rng()),v=rng();const q=clamp(.5+.15*(skill-tier)+Math.sqrt(-2*Math.log(u))*Math.cos(2*Math.PI*v)*.15,0,1);return q<.4?0:q<.7?1:q<.9?2:3};
F.lifespan=r=>sum(range(r+1).map(i=>P.LIFE_BASE*P.LIFE_GROWTH**i));
F.realm_time=r=>sum(range(STAGES[r]).map(s=>F.stage_time(r,s)));
F.aging_speed=r=>P.LIFE_BASE*P.LIFE_GROWTH**r*P.LIFE_USE/F.realm_time(r);
F.congphap_bonus=(sub,diff=0,mastery=1)=>P.CP_B0*2**sub*P.CP_MISMATCH**diff*(P.CP_MIN_MASTERY+(1-P.CP_MIN_MASTERY)*mastery);
F.congphap_total=items=>sum(items.map(x=>F.congphap_bonus(...x)).sort((a,b)=>b-a).slice(0,P.CP_SLOTS));
F.dan_exp_gain=(r,s,sub,used=0,diff=0)=>F.exp_need(r,s)*P.DAN_F0*2**sub*P.DAN_MISMATCH**diff/(1+used/P.DAN_DECAY_N);
F.dan_buff=x=>F.diminishing(x,P.BUFF_MAX,P.BUFF_K);
F.dan_buff_extra_exp=(rate,x,time)=>rate*F.dan_buff(x)*Math.max(0,time);
F.budget_multiplier=(cp,up=P.BUDGET_UP,dan=1)=>(1+cp)*up*(1+F.dan_buff(dan));
F.avg_stage_time=r=>F.realm_time(r)/STAGES[r];
F.income_rate=r=>P.INC_DAN_PER_STAGE*F.price_ha(r)/F.avg_stage_time(r);
F.income_by_source=r=>Object.fromEntries(Object.entries(D.INCOME_SHARE).map(([k,v])=>[k,F.income_rate(r)*v]));
F.kill_time=r=>F.avg_stage_time(r)/P.KILLS_PER_STAGE;
F.loot_ev=(r,kind='thường')=>F.income_rate(r)*D.INCOME_SHARE['quái']*F.kill_time(r)*D.LOOT_MULT[kind];
F.loot_linh_thach=(r,kind='thường')=>(1-P.YD_SHARE)*F.loot_ev(r,kind);
F.yeu_dan_value=(r,kind='thường')=>F.price_ha(r,D.YAO_SUB[kind]);
F.yeu_dan_drop_chance=(r,kind='thường')=>Math.min(1,P.YD_SHARE*F.loot_ev(r,kind)/F.yeu_dan_value(r,kind));
F.shop_buy_price=value=>value*P.SHOP_BUY_MARKUP;
F.shop_sell_price=value=>value*P.SHOP_SELL_RATIO;
F.auction_net=(value,factor=1)=>value*factor*(1-P.AUCTION_FEE);
F.barter_value=(value,kind)=>value*D.BARTER_LIQ[kind];
F.exp_per_ha=r=>F.ref_rate(r,0)/F.income_rate(r);
F.absorb_exp=(r,coin,count=1)=>count*P.ABSORB_EFF*D.COINS[coin][1]*F.exp_per_ha(r)*P.ABSORB_MISMATCH**Math.max(0,D.COIN_OF_REALM[r]-coin);
F.herb_price=(h,sub=0,age=null)=>{let p=P.BATCH_YIELD/(P.HERBS_PER_BATCH*P.DAN_MARGIN)*F.price_ha(h,sub);if(age&&D.HERB_AGE[h]){const [lo,hi]=D.HERB_AGE[h];p*=.7+.6*clamp(Math.log(age/lo)/Math.log(hi/lo),0,1)}return p};
F.dan_by_loai=type=>D.DAN_TABLE.filter(d=>d[3]===type);
F.dan_effect=(type,r,s,sub=0,used=0,diff=0)=>{const m=P.DAN_MISMATCH**diff,q=2**sub*m;switch(type){
case 'TU_VI':return {exp:F.dan_exp_gain(r,s,sub,used,diff)};
case 'BUFF_TOC':return {diem:P.DAN_BUFF_PT*q,buff_neu_mot_minh:F.dan_buff(P.DAN_BUFF_PT*q),thoi_luong:Math.max(60,P.DAN_BUFF_DUR*F.avg_stage_time(r))};
case 'DOT_PHA':return {diem:P.DOTPHA_PT*q,cong_xac_suat:F.diminishing(P.DOTPHA_PT*q,P.BONUS_MAX,P.BONUS_K)};
case 'KIEP':return {khien_theo_HP:P.KIEP_SHIELD*q,giam_sat_thuong:Math.min(P.KIEP_RED_MAX,P.KIEP_RED*q)};
case 'HOI_PHUC':return {hoi_phan_tram_HP:Math.min(1,P.HOIPHUC*q)};
case 'THO_NGUYEN':return {nam:P.THONGUYEN*P.LIFE_BASE*P.LIFE_GROWTH**r*q};
case 'CUNG_CO':return {cong_gop:P.CUNGCO*q,tran_moi_canh_gioi:P.CUNGCO_CAP};
case 'GIAI_DOC':return {giai_hieu_ung_xau:true};
case 'CHIEN_DAU':return {tang_ATK:P.CHIENDAU*q,thoi_luong:P.CHIENDAU_DUR};
case 'TRONG_SINH':return {giu_tien_do:Math.min(.8,P.TRONGSINH_KEEP*(sub+1)*m)};
default:throw Error('Unknown pill type: '+type)}};
F.realm_exp_total=r=>sum(range(STAGES[r]).map(s=>F.exp_need(r,s)));
F.dan_exp_gain_capped=(r,s,sub,used=0,fromPills=0,diff=0)=>Math.min(Math.max(0,P.DAN_REALM_CAP*F.realm_exp_total(r)-fromPills),F.dan_exp_gain(r,s,sub,used,diff));
F.cong_phap_realm=(pham,sub=0)=>D.PHAM_TIER[pham]+([4,5].includes(pham)?sub:0);
F.cong_phap_effect=(type,sub,diff=0,mastery=1)=>{const mm=P.CP_MIN_MASTERY+(1-P.CP_MIN_MASTERY)*mastery,q=2**sub*P.CP_MISMATCH**diff*mm;switch(type){case 'TOC':return {cong_gop_toc_do:P.CP_B0*q};case 'SAT':return {tang_ATK:P.CP_ATK*q};case 'PHONG':return {tang_HP_DEF:P.CP_DEFHP*q};case 'DAN':return {ky_nang_luyen_dan:P.CP_DAN_SKILL*(sub+1)*P.CP_MISMATCH**diff*mm};default:throw Error(type)}};
F.ascension_bolts=(r=4,rootType=null)=>{const n=D.ASCEND_BOLTS[r]||0,total=F.tribulation_total(r,rootType,P.ASCEND_TRIB_MULT);return range(n).map(k=>total/n*(.5+k/n))};
F.survive_ascension=(r,hp,shield=0,red=0,heal=0,rootType=null)=>{const bolts=F.ascension_bolts(r,rootType);return survive(bolts,hp,shield,red,heal,bolts.length)};
F.tribulation_events=r=>[...(BOLTS[r]?[[`Lôi kiếp ${REALMS[r]}`,BOLTS[r]]]:[]),...(D.ASCEND_BOLTS[r]?[['Phi Thăng Lôi Kiếp',D.ASCEND_BOLTS[r]]]:[])];
F.fmt=x=>{if(!Number.isFinite(x))return '—';const sign=x<0?'-':'';x=Math.abs(x);if(x>=1e36)return sign+x.toExponential(2);for(const [v,n] of [[1e32,'Câu'],[1e28,'Nhưỡng'],[1e24,'Tỷ'],[1e20,'Cai'],[1e16,'Kinh'],[1e12,'Triệu'],[1e8,'Ức'],[1e4,'Vạn']])if(x>=v)return sign+(x/v).toLocaleString('vi-VN',{maximumFractionDigits:2})+' '+n;return sign+x.toLocaleString('vi-VN',{maximumFractionDigits:1})};
F.format_linh_thach=x=>{if(x<1)return '0 Hạ';const i=D.COINS.findLastIndex(([,v])=>v<=x*(1+1e-12)),[name,value]=D.COINS[i],whole=Math.floor(x/value+1e-9);let out=F.fmt(whole)+' '+name;if(i>0){const [small,unit]=D.COINS[i-1],rest=Math.floor((x-whole*value)/unit+1e-9);if(rest>0)out+=' '+F.fmt(rest)+' '+small}return out};
root.HU_FORMULAS=Object.freeze(F);
if(typeof module!=='undefined'&&module.exports)module.exports=F;
})(typeof window!=='undefined'?window:globalThis);
